#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-3.0-only
"""Generates the Jubelle engine's style table (jubelle_engine/style/sid.h and styledefaults.cpp) from MuseScore's
style definitions, as dumped by the reference tool:

    JUBELLE_REFERENCE_STYLEDEFS=tools/jubelle_checks/data/musescore_style_defaults.txt \
        jet_ref --gtest_filter=Jubelle_Reference.StyleDefaults
    python3 tools/jubelle_checks/je_gen_style.py <MuseScore source>

It also generates the music symbol table (jubelle_engine/style/symid.h and symbols.cpp): MuseScore's symbol ids
(SymId, from its symbol names, in its order) with their SMuFL code points (fonts/smufl/glyphnames.json: the code
point and the alternate one in the Musical Symbols block, which MuseScore tries second).

The dump holds every value as MuseScore writes it in a file (<Style>), and the numbers exactly. The table keeps
MuseScore's names (Sid), so code ported from MuseScore's layout reads the same values, and each value's kind: a
number (booleans, integers, reals, spatium and millimetre values, and the enumerations MuseScore writes as numbers),
a text (strings and the enumerations MuseScore writes as names), a pair (points, sizes, scales) or a colour.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DUMP = os.path.join(HERE, 'data', 'musescore_style_defaults.txt')
OUT_H = os.path.join(REPO, 'jubelle_engine', 'style', 'sid.h')
OUT_CPP = os.path.join(REPO, 'jubelle_engine', 'style', 'styledefaults.cpp')
OUT_SYM_H = os.path.join(REPO, 'jubelle_engine', 'style', 'symid.h')
OUT_SYM_CPP = os.path.join(REPO, 'jubelle_engine', 'style', 'symbols.cpp')


def symbols(src):
    import json
    text = open(os.path.join(src, 'src', 'engraving', 'types', 'symnames.cpp'), encoding='utf-8').read()
    body = text[text.index('SymNames::s_symNames'):]
    body = body[body.index('{ {') + 3:body.index('} };')]
    body = re.sub(r'//[^\n]*', '', body)
    names = re.findall(r'"([^"]*)"', body)
    enum = open(os.path.join(src, 'src', 'engraving', 'types', 'symid_p.h'), encoding='utf-8').read()
    enum = enum[enum.index('enum class SymId'):]
    enum = enum[enum.index('{') + 1:enum.index('};')]
    enum = re.sub(r'/\*.*?\*/', '', re.sub(r'//[^\n]*', '', enum), flags=re.S)
    ids = [x.strip() for x in enum.split(',') if x.strip()]
    assert ids[-1] == 'lastSym' and len(ids) == len(names) + 1, (len(ids), len(names))
    glyphs = json.load(open(os.path.join(REPO, 'fonts', 'smufl', 'glyphnames.json'), encoding='utf-8'))
    with open(OUT_SYM_H, 'w', encoding='utf-8') as h:
        h.write('''/*
 * SPDX-License-Identifier: GPL-3.0-only
 * Jubelle engine (je::style). Not part of MuseScore.
 *
 * GENERATED by tools/jubelle_checks/je_gen_style.py from MuseScore's symbol names; do not edit.
 * MuseScore's music symbol ids (SymId), in MuseScore's order: the SMuFL names, then MuseScore's own.
 */
#pragma once

namespace je::style {
enum class SymId : int {
''')
        for i in ids:
            h.write(f'    {i},\n')
        h.write('};\nconstexpr int SYM_COUNT = int(SymId::lastSym);\n}\n')

    def cp(g, key):
        v = g.get(key, '') if g else ''
        return '0x' + v[2:] if v.startswith('U+') else '0'

    with open(OUT_SYM_CPP, 'w', encoding='utf-8') as c:
        c.write('''/*
 * SPDX-License-Identifier: GPL-3.0-only
 * Jubelle engine (je::style). Not part of MuseScore.
 *
 * GENERATED by tools/jubelle_checks/je_gen_style.py; do not edit.
 */
#include "font.h"

namespace je::style {
const SymbolCode SYMBOL_CODES[SYM_COUNT] = {
''')
        for n in names:
            g = glyphs.get(n)
            c.write(f'    {{ {cstr(n)}, {cp(g, "codepoint")}, {cp(g, "alternateCodepoint")} }},\n')
        c.write('};\n\n')
        ef = open(os.path.join(src, 'src', 'engraving', 'internal', 'engravingfont.cpp'), encoding='utf-8').read()
        b = ef[ef.index('GLYPHS_WITH_ALTERNATES[] = {'):]
        b = b[:b.index('};')]
        alts = re.findall(r'std::string\("([^"]+)"\),\s*std::string\("([^"]+)"\),\s*SymId::(\w+)', b)
        c.write('// MuseScore\'s EngravingFont GLYPHS_WITH_ALTERNATES: the alternates it uses, and for which symbol\n')
        c.write('const GlyphAlternate GLYPH_ALTERNATES[] = {\n')
        for k, a, sid in alts:
            c.write(f'    {{ {cstr(k)}, {cstr(a)}, SymId::{sid} }},\n')
        c.write('    { nullptr, nullptr, SymId::noSym },\n};\n\n')
        b = ef[ef.index('composedGlyphs[] = {'):]
        b = b[:b.index('\n    };')]
        c.write('// MuseScore\'s EngravingFont::loadComposedGlyphs\n')
        c.write('const ComposedGlyph COMPOSED_GLYPHS[7] = {\n')
        for m in re.finditer(r'\{\s*SymId::(\w+),\s*\{([^}]*)\}', b):
            subs = ', '.join('SymId::' + x for x in re.findall(r'SymId::(\w+)', m.group(2)))
            c.write(f'    {{ SymId::{m.group(1)}, {{ {subs} }} }},\n')
        c.write('};\n\n')
        acc = open(os.path.join(src, 'src', 'engraving', 'dom', 'accidental.cpp'), encoding='utf-8').read()
        b = acc[acc.index('static const Acc ACC_LIST[] = {'):]
        b = b[:b.index('};')]
        accs = re.findall(r'Acc\(AccidentalVal::(\w+),\s*([-0-9.]+),\s*SymId::(\w+)\)', b)
        vals = {'SHARP3': 3, 'SHARP2': 2, 'SHARP': 1, 'NATURAL': 0, 'FLAT': -1, 'FLAT2': -2, 'FLAT3': -3}
        c.write('// MuseScore\'s accidental types (AccidentalType, Accidental\'s ACC_LIST): alteration, cents, symbol\n')
        c.write('const AccidentalDef ACCIDENTALS[] = {\n')
        for v, cents, sym in accs:
            c.write(f'    {{ {vals[v]}, {cents}, SymId::{sym} }},\n')
        c.write('};\n')
        c.write(f'const int ACCIDENTAL_COUNT = {len(accs)};\n\n')
        key = open(os.path.join(src, 'src', 'engraving', 'dom', 'key.cpp'), encoding='utf-8').read()
        b = key[key.index('const SymId accTable[] = {'):]
        b = b[:b.index('};')]
        table = re.findall(r'SymId::(\w+)', b)
        c.write('// MuseScore\'s accTable (key.cpp): accidentals in order of alteration, for custom key signatures\n')
        c.write('const SymId ACCIDENTAL_ORDER[] = {\n')
        for sym in table:
            c.write(f'    SymId::{sym},\n')
        c.write('};\n')
        c.write(f'const int ACCIDENTAL_ORDER_COUNT = {len(table)};\n\n')
        cl = open(os.path.join(src, 'src', 'engraving', 'dom', 'clef.cpp'), encoding='utf-8').read()
        b = cl[cl.index('const ClefInfo ClefInfo::clefTable[] = {'):]
        b = b[:b.index('};')]
        clefs = re.findall(r'\{\s*ClefType::(\w+),\s*(-?\d+),\s*(-?\d+),\s*\{([^}]*)\},\s*SymId::(\w+),\s*StaffGroup::(\w+)\s*\}', b)
        tc = open(os.path.join(src, 'src', 'engraving', 'types', 'typesconv.cpp'), encoding='utf-8').read()
        b = tc[tc.index('CLEF_TYPES = {'):]
        b = b[:b.index('};')]
        tags = dict(re.findall(r'\{\s*ClefType::(\w+),\s*"([^"]*)"', b))
        c.write('// MuseScore\'s clefs (ClefInfo::clefTable, with the names files use): line, pitch offset, key signature lines\n')
        c.write('// (sharps, then flats), symbol, staff group\n')
        c.write('const ClefDef CLEFS[] = {\n')
        for t, line, off, lines, sym, group in clefs:
            ls = ', '.join(x.strip() for x in lines.split(','))
            c.write(f'    {{ {cstr(tags.get(t, t))}, {line}, {off}, {{ {ls} }}, SymId::{sym}, {cstr(group.lower())} }},\n')
        c.write('    { nullptr, 0, 0, {}, SymId::noSym, nullptr },\n};\n}\n')
        print(f'{len(clefs)} clefs')
        print(f'{len(alts)} alternates, {len(accs)} accidentals')
    print(f'{len(names)} symbols')

# types MuseScore writes as names (MStyle::save: TConv::toXml, LINE_TYPE through tagProperty)
TEXT_TYPES = {'STRING', 'ALIGN', 'ALIGN_H', 'LINE_TYPE', 'TIE_PLACEMENT', 'TIE_DOTS_PLACEMENT', 'TIMESIG_PLACEMENT',
              'TIMESIG_STYLE', 'TIMESIG_MARGIN', 'CHORD_PRESET_TYPE', 'NOTE_SPELLING_TYPE', 'LH_TAPPING_SYMBOL',
              'RH_TAPPING_SYMBOL', 'TEXT_STYLE', 'PARENTHESES_MODE', 'PLAY_COUNT_PRESET', 'MEASURE_NUMBER_PLACEMENT'}
PAIR_TYPES = {'POINT': ('x', 'y'), 'SIZE': ('w', 'h'), 'SCALE': ('w', 'h')}


def ptypes(header):
    src = open(header, encoding='utf-8').read()
    body = re.search(r'enum class P_TYPE[^{]*\{(.*?)\};', src, re.S).group(1)
    body = re.sub(r'//[^\n]*', '', body)
    names = [n.strip().split('=')[0].strip() for n in body.split(',')]
    return [n for n in names if n]


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def num(v):
    r = repr(float(v))
    return r if ('.' in r or 'e' in r or 'inf' in r or 'nan' in r) else r + '.0'


def main():
    types = ptypes(os.path.join(sys.argv[1], 'src', 'engraving', 'types', 'propertyvalue.h'))
    symbols(sys.argv[1])
    text = open(DUMP, encoding='utf-8').read()
    style_xml = text.split('#style\n', 1)[1].split('\n#types\n', 1)[0]
    after = text.split('\n#types\n', 1)[1]
    types_part, rest = after.split('#align\n', 1)
    align_part, symsize_part = rest.split('#symsize\n', 1)
    symsize_part, hf_part = symsize_part.split('#noteheads\n', 1)
    heads_part, hf_part = hf_part.split('#headerfooter\n', 1)
    heads = [line.split('\t') for line in heads_part.splitlines() if line]
    headerfooter = [line.split('\t') for line in hf_part.splitlines() if line]
    rows = [line.split('\t') for line in types_part.splitlines() if line]
    aligns = [line.split('\t') for line in align_part.splitlines() if line]
    symsizes = [line.split('\t') for line in symsize_part.splitlines() if line]
    root = ET.fromstring(style_xml)
    written = {}
    for e in root:
        written[e.tag] = e
    entries = []
    for name, t, exact in rows:
        tname = types[int(t)]
        e = written.get(name)
        kind, a, b, txt = 'Number', 0.0, 0.0, ''
        if tname in PAIR_TYPES:
            kind = 'Pair'
            if exact:
                a, b = (float(x) for x in exact.split())
            else:
                ka, kb = PAIR_TYPES[tname]
                a, b = float(e.get(ka, 0)), float(e.get(kb, 0))
        elif tname == 'COLOR':
            kind = 'Color'
            a = float((int(e.get('r')) << 24) | (int(e.get('g')) << 16) | (int(e.get('b')) << 8) | int(e.get('a', 255)))
        elif tname in TEXT_TYPES:
            kind = 'Text'
            txt = (e.text or '') if e is not None else ''
        elif name == 'spatium':
            a = float(exact)                        # engraving units (1/1200 inch): kept as MuseScore holds it
        else:
            a = float(exact) if exact else float((e.text or '0').strip() or 0)
        entries.append((name, tname, kind, a, b, txt))

    with open(OUT_H, 'w', encoding='utf-8') as h:
        h.write('''/*
 * SPDX-License-Identifier: GPL-3.0-only
 * Jubelle engine (je::style). Not part of MuseScore.
 *
 * GENERATED by tools/jubelle_checks/je_gen_style.py from MuseScore's style definitions; do not edit.
 * MuseScore's style value names (Sid), in MuseScore's order.
 */
#pragma once

namespace je::style {
enum class Sid : int {
''')
        for name, *_ in entries:
            h.write(f'    {name},\n')
        h.write('    STYLES,\n    NOSTYLE = -1,\n};\n}\n')

    with open(OUT_CPP, 'w', encoding='utf-8') as c:
        c.write('''/*
 * SPDX-License-Identifier: GPL-3.0-only
 * Jubelle engine (je::style). Not part of MuseScore.
 *
 * GENERATED by tools/jubelle_checks/je_gen_style.py from MuseScore's style definitions; do not edit.
 */
#include "font.h"
#include "style.h"

namespace je::style {
const StyleDef STYLE_DEFS[] = {
''')
        for name, tname, kind, a, b, txt in entries:
            c.write(f'    {{ {cstr(name)}, ValueKind::{kind}, {cstr(tname)}, {num(a)}, {num(b)}, {cstr(txt)} }},\n')
        c.write('};\n\n')
        c.write('// MuseScore\'s CompatUtils::ALIGN_VALS_TO_CONVERT: the position value set from each alignment before 4.6\n')
        c.write('const std::pair<Sid, Sid> ALIGN_POSITIONS[] = {\n')
        for a, b in aligns:
            c.write(f'    {{ Sid::{a}, Sid::{b} }},\n')
        c.write('    { Sid::NOSTYLE, Sid::NOSTYLE },\n};\n\n')
        c.write('// The text styles\' music symbol size and font size (CompatUtils::setMusicSymbolSize470); the tempo\'s is 5/3\n')
        c.write('const SymbolSizeStyle SYMBOL_SIZE_STYLES[] = {\n')
        for a, b, t in symsizes:
            c.write(f'    {{ Sid::{a}, Sid::{b}, {"true" if t == "1" else "false"} }},\n')
        c.write('    { Sid::NOSTYLE, Sid::NOSTYLE, false },\n};\n\n')
        c.write('// MuseScore\'s notehead table (Note::noteHead): each group, by head type (whole, half, quarter, breve), down and up\n')
        c.write('const NoteheadGroup NOTEHEAD_GROUPS[] = {\n')
        for row in heads:
            syms = row[1:]
            pairs = ', '.join('{ SymId::' + syms[2 * i] + ', SymId::' + syms[2 * i + 1] + ' }' for i in range(len(syms) // 2))
            c.write(f'    {{ {cstr(row[0])}, {{ {{ {pairs} }} }} }},\n')
        c.write('    { nullptr, {} },\n};\n\n')
        c.write('// The header, footer, copyright and page number text styles, entry by entry (CompatUtils::mapHeaderFooterStyles)\n')
        c.write('const std::array<Sid, 4> HEADER_FOOTER_STYLES[] = {\n')
        for row in headerfooter:
            c.write('    { ' + ', '.join('Sid::' + x for x in row) + ' },\n')
        c.write('    { Sid::NOSTYLE, Sid::NOSTYLE, Sid::NOSTYLE, Sid::NOSTYLE },\n};\n\n')
        # the defaults of scores written with 4.5's (defaultsVersion 450), one line each (compilers limit literals)
        legacy = os.path.join(REPO, 'src', 'engraving', 'data', 'styles', 'legacy-style-defaults-v450.mss')
        c.write('// MuseScore\'s src/engraving/data/styles/legacy-style-defaults-v450.mss\n')
        c.write('extern const char* const LEGACY_STYLE_V450[] = {\n')
        for line in open(legacy, encoding='utf-8').read().splitlines():
            c.write(f'    {cstr(line.strip())},\n')
        c.write('    nullptr,\n};\n}\n')
    print(f'{len(entries)} style values')


if __name__ == '__main__':
    main()
